use std::collections::BTreeMap;
use std::fs;
use std::mem;
use std::path::{Path, PathBuf};

#[allow(clippy::print_stdout)]
pub fn process_crate(manifest_dir: &str, out_dir: &str) {
    let icons_dir = Path::new(manifest_dir).join("icons");
    let mut files = Vec::new();
    collect_svgs(&icons_dir, &mut files);
    files.sort();

    let mut root = Module::default();
    let mut seen: BTreeMap<String, PathBuf> = BTreeMap::new();
    let remote_names = remote_stems(Path::new(manifest_dir));
    for file in &files {
        let relative = file
            .strip_prefix(&icons_dir)
            .expect("file under icons dir")
            .to_path_buf();
        let source = fs::read_to_string(file)
            .unwrap_or_else(|err| panic!("requiem-icons: reading {}: {err}", file.display()));
        let path_data = parse_svg(&source)
            .unwrap_or_else(|err| panic!("requiem-icons: {}: {err}", file.display()));

        let mut modules: Vec<String> = relative
            .parent()
            .map(|p| {
                p.components()
                    .map(|c| to_snake(&c.as_os_str().to_string_lossy()))
                    .collect()
            })
            .unwrap_or_default();
        let name = to_screaming(
            file.file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or_default(),
        );
        let key = format!("{}::{name}", modules.join("::"));
        if let Some(previous) = seen.insert(key, file.clone()) {
            panic!(
                "requiem-icons: {} and {} both generate `{name}` — rename one of the files",
                previous.display(),
                file.display()
            );
        }
        let mut module = &mut root;
        for part in modules.drain(..) {
            module = module.children.entry(part).or_default();
        }
        module.icons.insert(
            name,
            (
                relative.to_string_lossy().replace('\\', "/"),
                IconSource::Local(path_data),
            ),
        );
    }

    for stem in &remote_names {
        let name = remote_const_name(stem);
        if let Some(local) = seen.get(&format!("::{name}")) {
            panic!(
                "requiem-icons: recipes.rs names `{stem}` but {} already generates `{name}`",
                local.display()
            );
        }
        if root
            .icons
            .insert(
                name.clone(),
                (
                    "remote.txt".to_string(),
                    IconSource::Remote(format!("icon/{stem}")),
                ),
            )
            .is_some()
        {
            panic!("requiem-icons: `{stem}` appears twice in recipes.rs");
        }
    }

    let mut out = String::from(
        "// AUTO-GENERATED by requiem-icons from `icons/**/*.svg` at build time — do not edit.\n",
    );
    render(&root, 0, &mut out);
    out.push_str("pub const ALL: &[(&str, Icon)] = &[\n");
    let mut components: BTreeMap<String, String> = BTreeMap::new();
    for (name, (source, icon)) in &root.icons {
        let stem = match icon {
            IconSource::Remote(asset) => asset.rsplit('/').next().unwrap_or(asset).to_string(),
            IconSource::Local(_) => Path::new(source)
                .file_stem()
                .map(|s| s.to_string_lossy().into_owned())
                .unwrap_or_default(),
        };
        let component = component_name(&stem);
        if let Some(previous) = components.insert(component.clone(), name.clone()) {
            panic!("requiem-icons: `{previous}` and `{name}` both become the component `{component}`");
        }
        out.push_str(&format!("    (\"{component}\", {name}),\n"));
    }
    out.push_str("];\n");
    fs::write(Path::new(out_dir).join("requiem_icons.rs"), out)
        .expect("requiem-icons: writing requiem_icons.rs");
    println!("cargo:rerun-if-changed=build.rs");
}

enum IconSource {
    Local(String),

    Remote(String),
}

#[derive(Default)]
struct Module {
    icons: BTreeMap<String, (String, IconSource)>,
    children: BTreeMap<String, Module>,
}

fn remote_stems(manifest_dir: &Path) -> Vec<String> {
    let path = manifest_dir.join("../requiem-assets/src/recipes.rs");
    let text = fs::read_to_string(&path)
        .unwrap_or_else(|err| panic!("requiem-icons: reading {}: {err}", path.display()));
    let mut stems = Vec::new();
    // rustfmt breaks a long call after its opening parenthesis and puts the key on the next line.
    let mut call_open = false;
    for line in text.lines() {
        let trimmed = line.trim();
        let after_open = mem::replace(
            &mut call_open,
            matches!(trimmed, "icon(" | "by_markup(" | "by_path("),
        );
        let rest = trimmed
            .strip_prefix("icon(\"icon/")
            .or_else(|| trimmed.strip_prefix("by_markup(\"icon/"))
            .or_else(|| trimmed.strip_prefix("by_path(\"icon/"))
            .or_else(|| {
                trimmed
                    .strip_prefix("\"icon/")
                    .filter(|_| after_open || trimmed.contains("Win"))
            });
        let Some(rest) = rest else {
            continue;
        };
        let Some(stem) = rest.split('"').next() else {
            continue;
        };
        if stem.is_empty() {
            continue;
        }
        stems.push(stem.to_string());
    }
    stems.sort();
    stems.dedup();
    stems
}

fn render(module: &Module, depth: usize, out: &mut String) {
    let pad = "    ".repeat(depth);
    for (name, (source, icon)) in &module.icons {
        match icon {
            IconSource::Local(data) => {
                out.push_str(&format!("{pad}/// From `icons/{source}`.\n{pad}pub const {name}: Icon = Icon::Local({data:?});\n"));
            }
            IconSource::Remote(asset) => {
                out.push_str(&format!("{pad}/// Discord's icon `{asset}`, resolved at runtime.\n{pad}pub const {name}: Icon = Icon::Named({asset:?});\n"));
            }
        }
    }
    for (name, child) in &module.children {
        out.push_str(&format!("{pad}pub mod {name} {{\n"));
        render(child, depth + 1, out);
        out.push_str(&format!("{pad}}}\n"));
    }
}

fn collect_svgs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_svgs(&path, out);
        } else if path.extension().and_then(|e| e.to_str()) == Some("svg") {
            out.push(path);
        }
    }
}

fn component_name(stem: &str) -> String {
    let mut out = String::new();
    for part in stem.split(['_', '-']).filter(|part| !part.is_empty()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if !out.ends_with("Icon") {
        out.push_str("Icon");
    }
    out
}

fn remote_const_name(stem: &str) -> String {
    if !stem.contains(|c: char| c.is_ascii_uppercase()) {
        return to_screaming(stem);
    }
    let base = stem.strip_suffix("Icon").unwrap_or(stem);
    let chars: Vec<char> = base.chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        let after_lower =
            i > 0 && (chars[i - 1].is_ascii_lowercase() || chars[i - 1].is_ascii_digit());
        let starts_word = i > 0
            && chars[i - 1].is_ascii_uppercase()
            && chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
        if c.is_ascii_uppercase() && (after_lower || starts_word) {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    to_screaming(&out)
}

fn to_screaming(kebab: &str) -> String {
    let name = kebab.replace(['-', ' '], "_").to_ascii_uppercase();

    if name.starts_with(|c: char| c.is_ascii_digit()) {
        format!("I_{name}")
    } else {
        name
    }
}

fn to_snake(kebab: &str) -> String {
    kebab.replace(['-', ' '], "_").to_ascii_lowercase()
}

fn attributes(tag: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let bytes = tag.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let start = i;
        while i < bytes.len()
            && (bytes[i].is_ascii_alphanumeric() || matches!(bytes[i], b'-' | b':' | b'_'))
        {
            i += 1;
        }
        let name = &tag[start..i];
        if i < bytes.len() && bytes[i] == b'=' && !name.is_empty() {
            i += 1;
            if i < bytes.len() && (bytes[i] == b'"' || bytes[i] == b'\'') {
                let quote = bytes[i];
                i += 1;
                let value_start = i;
                while i < bytes.len() && bytes[i] != quote {
                    i += 1;
                }
                out.push((name.to_string(), tag[value_start..i].to_string()));
            }
        }
        i += 1;
    }
    out
}

pub fn parse_svg(svg: &str) -> Result<String, String> {
    let mut paths: Vec<String> = Vec::new();
    let mut saw_svg = false;
    let mut rest = svg;
    while let Some(open) = rest.find('<') {
        rest = &rest[open + 1..];

        if rest.starts_with("!--") {
            rest = rest.find("-->").map_or("", |end| &rest[end + 3..]);
            continue;
        }
        if rest.starts_with('?') || rest.starts_with('/') || rest.starts_with('!') {
            continue;
        }
        let end = rest.find('>').ok_or("unterminated tag")?;
        let tag = &rest[..end];
        let name_end = tag
            .find(|c: char| c.is_whitespace() || c == '/')
            .unwrap_or(tag.len());
        let (name, attrs) = (&tag[..name_end], attributes(&tag[name_end..]));
        match name {
            "svg" => {
                saw_svg = true;
                let view_box = attrs
                    .iter()
                    .find(|(k, _)| k == "viewBox")
                    .map(|(_, v)| v.split_whitespace().collect::<Vec<_>>().join(" "));
                if view_box.as_deref() != Some("0 0 24 24") {
                    return Err(format!(
                        "viewBox must be \"0 0 24 24\" (the engine draws 24x24 icons), found {view_box:?}"
                    ));
                }
            }
            "path" => {
                let d = attrs
                    .iter()
                    .find(|(k, _)| k == "d")
                    .map(|(_, v)| v.trim().to_string())
                    .ok_or("a <path> has no d attribute")?;
                if d.is_empty() {
                    return Err("a <path> has an empty d attribute".to_string());
                }
                if attrs.iter().any(|(k, _)| k == "transform") {
                    return Err("a <path> has a transform, which isn't supported".to_string());
                }
                paths.push(d);
            }
            "g" => {
                if attrs.iter().any(|(k, _)| k == "transform") {
                    return Err("a <g> has a transform, which isn't supported".to_string());
                }
            }
            "title" | "desc" | "defs" => {}
            other => {
                return Err(format!(
                    "<{other}> isn't supported — an icon may contain only <path> elements (convert shapes to paths)"
                ));
            }
        }
        rest = &rest[end + 1..];
    }
    if !saw_svg {
        return Err("no <svg> element".to_string());
    }
    if paths.is_empty() {
        return Err("no <path> elements".to_string());
    }

    for path in paths.iter_mut().skip(1) {
        if let Some(rest) = path.strip_prefix('m') {
            *path = format!("M{rest}");
        }
    }
    Ok(paths.join(" "))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_single_path_icon_yields_its_data() {
        let svg = r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor"><path d="M1 2h3"/></svg>"#;
        assert_eq!(parse_svg(svg).unwrap(), "M1 2h3");
    }

    #[test]
    fn later_paths_start_absolute() {
        let svg = r#"<svg viewBox="0 0 24 24"><path d="M0 0h1"/><path d="m5 5h1"/></svg>"#;
        assert_eq!(parse_svg(svg).unwrap(), "M0 0h1 M5 5h1");
    }

    #[test]
    fn unsupported_content_is_rejected_by_name() {
        assert!(
            parse_svg(r#"<svg viewBox="0 0 24 24"><circle cx="1" cy="1" r="1"/></svg>"#)
                .unwrap_err()
                .contains("<circle>")
        );
        assert!(
            parse_svg(r#"<svg viewBox="0 0 16 16"><path d="M0 0"/></svg>"#)
                .unwrap_err()
                .contains("viewBox")
        );
        assert!(
            parse_svg(r#"<svg viewBox="0 0 24 24"><path d="M0 0" transform="scale(2)"/></svg>"#)
                .unwrap_err()
                .contains("transform")
        );
        assert!(
            parse_svg(r#"<svg viewBox="0 0 24 24"></svg>"#)
                .unwrap_err()
                .contains("no <path>")
        );
    }

    #[test]
    fn names_follow_the_file_name() {
        assert_eq!(to_screaming("arrow-left"), "ARROW_LEFT");
        assert_eq!(to_snake("Nav-Icons"), "nav_icons");
    }
}
